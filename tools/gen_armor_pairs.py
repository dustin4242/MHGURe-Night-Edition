#!/usr/bin/env python3
"""Generate runtime/hle/armor_pairs.h from armorSeriesData.asd.

Each 127-byte series record has two class bytes at +0x0f/+0x10:
(1, 0) Blademaster-only, (0, 1) Gunner-only, (1, 1) both, (0, 0) neither.
Every split series has exactly one counterpart of the other class.  The
records are otherwise nearly identical, so the counterpart is the record of
the other class with the fewest differing bytes (offsets 4..126).

Usage: python3 tools/gen_armor_pairs.py [armorSeriesData.asd] [output.h]
"""

import sys

ASD = "mhgu/romfs/nativeNX/table/armorSeriesData.asd"
OUT = "runtime/hle/armor_pairs.h"
RECORD = 127
HEADER = 8


def main() -> None:
    src = sys.argv[1] if len(sys.argv) > 1 else ASD
    dst = sys.argv[2] if len(sys.argv) > 2 else OUT
    data = open(src, "rb").read()
    count = (len(data) - HEADER) // RECORD
    records = [data[HEADER + i * RECORD : HEADER + (i + 1) * RECORD] for i in range(count)]

    classes = []
    for rec in records:
        blade, gunner = rec[0x0F], rec[0x10]
        classes.append(1 if (blade, gunner) == (1, 0) else 2 if (blade, gunner) == (0, 1) else 0)

    blade = [i for i, c in enumerate(classes) if c == 1]
    gunner = [i for i, c in enumerate(classes) if c == 2]
    pair = [0xFFFF] * count

    def distance(i: int, j: int) -> int:
        a, b = records[i], records[j]
        return sum(1 for k in range(4, RECORD) if a[k] != b[k])

    for i in blade:
        j = min(gunner, key=lambda j: distance(i, j))
        if pair[i] != 0xFFFF or pair[j] != 0xFFFF or classes[j] != 2:
            raise SystemExit(f"ambiguous pair for series {i}")
        pair[i], pair[j] = j, i

    with open(dst, "w") as f:
        f.write("// Generated by tools/gen_armor_pairs.py from mhgu/romfs/nativeNX/table/armorSeriesData.asd.\n")
        f.write("// class: 0 both/neither, 1 Blademaster-only, 2 Gunner-only; pair: the other class series, 0xffff if none.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define ARMOR_SERIES_COUNT {count}\n\n")
        f.write("static const uint8_t armor_series_class[ARMOR_SERIES_COUNT] = {\n")
        for i in range(0, count, 32):
            f.write("    " + ",".join(str(x) for x in classes[i : i + 32]) + ",\n")
        f.write("};\n\nstatic const uint16_t armor_series_pair[ARMOR_SERIES_COUNT] = {\n")
        for i in range(0, count, 16):
            f.write("    " + ",".join("0xffff" if x == 0xFFFF else str(x) for x in pair[i : i + 16]) + ",\n")
        f.write("};\n")

    print(f"{count} series, {len(blade)} pairs -> {dst}")


if __name__ == "__main__":
    main()
